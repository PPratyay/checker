/* Valid C layout example. */

/* ============================================================================ */
/*                              Include Files                                  */
/* ============================================================================ */
#include <stddef.h>

/* ============================================================================ */
/*                                  Macros                                     */
/* ============================================================================ */
#define BUFFER_SIZE 16

/* ============================================================================ */
/*                                 Typedefs                                    */
/* ============================================================================ */
typedef unsigned int item_count_t;

/* ============================================================================ */
/*                           Structure Declarations                            */
/* ============================================================================ */
struct item {
    item_count_t count;
};

/* ============================================================================ */
/*                            Extern Variables                                 */
/* ============================================================================ */
int shared_value;

/* ============================================================================ */
/*                            Static Variables                                 */
/* ============================================================================ */
static int local_value;

/* ============================================================================ */
/*                          Function Declarations                              */
/* ============================================================================ */
void process_item(void);

/* ============================================================================ */
/*                        Static Function Prototypes                           */
/* ============================================================================ */
static void reset_item(void);

/* ============================================================================ */
/*                           Function Definitions                              */
/* ============================================================================ */
void process_item(void)
{
    shared_value = BUFFER_SIZE;
}

/* ============================================================================ */
/*                      Static Function Definitions                            */
/* ============================================================================ */
static void reset_item(void)
{
    local_value = 0;
}
